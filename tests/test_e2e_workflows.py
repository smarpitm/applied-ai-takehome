def _char_ngram_embed(texts: Sequence[str]) -> list[list[float]]:
    """Deterministic char 3-gram 384-dim embedder so lexical overlap works in offline E2E tests."""
    import hashlib

    vecs: list[list[float]] = []
    for text in texts:
        vec = [0.0] * 384
        norm_text = f" {text.lower()} "
        for i in range(max(1, len(norm_text) - 2)):
            gram = norm_text[i : i + 3]
            idx = int(hashlib.md5(gram.encode()).hexdigest(), 16) % 384
            vec[idx] += 1.0
        norm = sum(x * x for x in vec) ** 0.5 or 1.0
        vecs.append([x / norm for x in vec])
    return vecs


def test_p1_e2e_evaluation_pipeline(tmp_path: Path) -> None:
    corpus_dir = tmp_path / "corpus"
    generate_corpus(corpus_dir)

    questions = [
        {
            "id": "e2e_q1",
            "question": (
                "How many bytes does one 384-dim vector occupy and which model generates it?"
            ),
            "relevant_chunk_ids": [make_chunk_id("architecture/vector_storage_overview.md", 0)],
            "relevant_sources": ["architecture/vector_storage_overview.md"],
            "answer_keywords": ["1,536 bytes"],
            "filters": None,
            "gold_answer": "1,536 bytes generated by BAAI/bge-small-en-v1.5.",
            "unanswerable": False,
        },
        {
            "id": "e2e_q2",
            "question": "What is on the cafeteria lunch menu in Tokyo?",
            "relevant_chunk_ids": [],
            "relevant_sources": [],
            "answer_keywords": [],
            "filters": None,
            "gold_answer": "Unanswerable.",
            "unanswerable": True,
        },
    ]
    q_path = tmp_path / "questions.json"
    q_path.write_text(json.dumps(questions), encoding="utf-8")

    def fake_transport(
        provider: str,
        model: str,
        messages: list[dict[str, str]],
        temperature: float,
        max_tokens: int,
        json_mode: bool,
    ) -> tuple[str, int, int]:
        if json_mode:
            return (
                json.dumps(
                    {
                        "evidence_quotes": ["1,536 bytes"],
                        "faithfulness_rationale": "Grounded in context.",
                        "faithfulness_score": 5,
                        "relevance_rationale": "Directly answers question.",
                        "relevance_score": 5,
                    }
                ),
                120,
                40,
            )
        cid = make_chunk_id("architecture/vector_storage_overview.md", 0)
        return f"1,536 bytes generated by BAAI/bge-small-en-v1.5 [{cid}].", 180, 20

    settings = Settings(
        lancedb_path=tmp_path / "lancedb",
        qdrant_path=tmp_path / "qdrant",
        qdrant_url=None,
        log_dir=tmp_path / "logs",
        groq_api_key="dummy",
        gemini_api_key="dummy",
        min_similarity_score=0.50,
    )
    embedder = LocalEmbedder(dim=384, embed_fn=_char_ngram_embed)
    router = LLMRouter(settings=settings, transport=fake_transport)
    store = LanceVectorStore(db_path=settings.lancedb_path, embedding_dim=384)
    svc = RAGService(settings=settings, embedder=embedder, lance_store=store, router=router)

    out_dir = tmp_path / "results"
    summary = run_full_evaluation(
        corpus_dir=corpus_dir,
        questions_path=q_path,
        out_dir=out_dir,
        k=3,
        settings=settings,
        service=svc,
        sync_qdrant=True,
        run_scale_bench=False,
    )
    assert summary["idempotency_check"]["zero_duplicate_vectors"] is True
    assert summary["answer_quality"]["no_context_refusal_accuracy"] == 1.0
    assert summary["answer_quality"]["mean_faithfulness_1_to_5"] == 5.0
    assert (out_dir / "p1_eval_results.json").exists()
    assert (out_dir / "p1_cost_comparison.md").exists()


def test_p2_e2e_bias_validation_and_ab(tmp_path: Path) -> None:
    def smart_judge(
        provider: str,
        model: str,
        messages: list[dict[str, str]],
        temperature: float,
        max_tokens: int,
        json_mode: bool,
    ) -> tuple[str, int, int]:
        sys_prompt = messages[0]["content"]
        user_msg = messages[-1]["content"]
        mitigated = "CRITICAL RULES:" in sys_prompt

        if "Mode: Pointwise" in user_msg:
            is_wrong = "3,072" in user_msg or "509" in user_msg or "Marcus Vance" in user_msg
            # Baseline gets fooled by sycophancy; mitigated catches wrong facts
            score = 4 if (is_wrong and not mitigated) else (1 if is_wrong else 5)
            crit = {
                "quoted_evidence": ["quote"],
                "rationale": "Checked facts against reference.",
                "score": score,
            }
            return (
                json.dumps(
                    {
                        "criteria": {
                            "correctness": crit,
                            "faithfulness": crit,
                            "completeness": crit,
                            "instruction_following": crit,
                            "conciseness": crit,
                            "safety": {**crit, "score": 5},
                        },
                        "overall_rationale": "Evaluated.",
                    }
                ),
                100,
                40,
            )

        part_a = user_msg.split("--- Candidate A ---")[1].split("--- Candidate B ---")[0]
        part_b = user_msg.split("--- Candidate B ---")[1].split("Required JSON Schema")[0]
        if not mitigated:
            # Baseline prefers longer padded text
            winner = "A" if len(part_a) >= len(part_b) else "B"
        else:
            # Mitigated penalizes filler and rewards ground-truth match
            if "Thank you so much" in part_a and "Thank you so much" not in part_b:
                winner = "B"
            elif "Thank you so much" in part_b and "Thank you so much" not in part_a:
                winner = "A"
            else:
                winner = "A" if "[c1]" in part_a else ("B" if "[c1]" in part_b else "A")
        sa, sb = (5, 3) if winner == "A" else (3, 5)
        crit = {
            "quoted_evidence_a": ["a"],
            "quoted_evidence_b": ["b"],
            "rationale": "Compared candidates.",
            "score_a": sa,
            "score_b": sb,
        }
        return (
            json.dumps(
                {
                    "criteria": {
                        "correctness": crit,
                        "faithfulness": crit,
                        "completeness": crit,
                        "instruction_following": crit,
                        "conciseness": crit,
                        "safety": crit,
                    },
                    "overall_rationale": "Done.",
                    "winner": winner,
                }
            ),
            120,
            50,
        )

    settings = Settings(gemini_api_key="dummy", groq_api_key="dummy", log_dir=tmp_path / "logs")
    router = LLMRouter(settings=settings, transport=smart_judge)
    engine = JudgeEngine(router=router, settings=settings, audit_log_path=tmp_path / "trace.jsonl")

    main_cases = [
        TestCase(
            id=f"c{i}",
            input="Q",
            expected_output="48 bytes [c1]",
            model_output="48 bytes [c1]",
            gold_pass=True,
            output_a="48 bytes [c1]",
            output_b="Wrong",
            gold_winner="A",
        )
        for i in range(6)
    ]
    verb_pairs = [
        {
            "id": "v1",
            "input": "Q",
            "expected_output": "48 bytes",
            "concise_accurate": "48 bytes.",
            "padded_accurate": "Thank you so much! 48 bytes.",
        }
    ]
    probes = [
        TestCase(
            id="p1",
            category="confident_hallucination",
            input="Q",
            expected_output="99.95%",
            model_output="99.95% overseen by Marcus Vance.",
            gold_pass=False,
        )
    ]

    bias = run_all_bias_experiments(
        main_cases=main_cases,
        verbosity_pairs=verb_pairs,
        probes=probes,
        router=router,
        settings=settings,
        audit_log_path=tmp_path / "trace.jsonl",
    )
    assert bias["details"]["verbosity"]["baseline_padded_win_rate"] == 1.0
    assert bias["details"]["verbosity"]["mitigated_padded_win_rate"] == 0.0
    assert bias["details"]["sycophancy"]["baseline_false_pass_rate"] == 1.0
    assert bias["details"]["sycophancy"]["mitigated_false_pass_rate"] == 0.0

    gold = run_gold_agreement_validation(engine, main_cases)
    assert gold["pointwise_cohens_kappa"] == 1.0
    adv = run_adversarial_probe_validation(engine, probes)
    assert adv["mitigated_fooled_rate"] == 0.0
    retest = run_test_retest_validation(engine, main_cases, repeats=3)
    assert retest["test_retest_flip_rate"] == 0.0

    ab_data = {
        "config_a": {"name": "v1", "system_prompt": "Answer."},
        "config_b": {"name": "v2", "system_prompt": "Cite."},
        "cases": [
            {
                "id": f"ab{i}",
                "input": "Q",
                "expected_output": "48 bytes [c1]",
                "output_a": "Small",
                "output_b": "48 bytes [c1]",
            }
            for i in range(7)
        ],
    }
    ab = run_ab_comparison(ab_data, engine=engine, settings=settings)
    assert ab["declared_winner"] == "v2"
